'use strict';
const assert=require('node:assert/strict');
const ai=require('../route-ai.js');
const mk=(name,id=name)=>({id,tags:{name}});
const park=[mk('Парк Победы'),mk('Городской сквер')];
const culture=[mk('Памятник защитникам'),mk('Исторический музей')];
const nature=[mk('Берег реки Лены'),mk('Лесной экотропа')];
const storage={data:{},getItem(k){return this.data[k]??null;},setItem(k,v){this.data[k]=v}};
global.localStorage=storage;
ai.resetForTests();
assert.equal(ai.category('Парк культуры'),'parks');
assert.equal(ai.category('Исторический музей'),'city');
assert.equal(ai.category('Берег реки'),'nature');
assert.ok(ai.score(park,'parks')>ai.score(culture,'parks'),'preferred parks should win');
assert.ok(ai.score(culture,'city')>ai.score(park,'city'),'preferred city should win');
assert.ok(ai.score(nature,'nature')>ai.score(culture,'nature'),'preferred nature should win');
const before=ai.score(park,'parks');
const m=ai.learnCompleted(park,'parks');
assert.equal(m.completed,1);
assert.equal(ai.load(storage).completed,1,'model learned from verified finish');
assert.ok(ai.load(storage).seen.includes('парк победы'));
assert.ok(ai.score(park,'parks')<before,'repeated landmarks should be less novel');
assert.ok(ai.score([mk('Новый парк'),mk('Центральный сквер')],'parks')>ai.score(park,'parks'),'unvisited places should be rewarded');
ai.learnCompleted(culture,'city',storage);
assert.equal(ai.load(storage).completed,2);
ai.resetForTests();
assert.equal(ai.load(storage).completed,2,'learning persists across reload');
assert.deepEqual(ai.features([], 'parks'),[0,0,0]);
assert.equal(ai.nameOf({tags:{name:'Точка'}}),'Точка');
assert.equal(ai.load({getItem:()=>'{broken'}).completed,0);
console.log('Route AI: local online learning, requested interests, novelty, repeat penalty and storage OK');
