'use strict';
const assert=require('node:assert/strict');
const nav=require('../route-navigation.js');
const p=[62,129],e=[62,129.001],n=[62.001,129.001],s=[61.999,129.001];
assert.ok(nav.metres(p,e)>45&&nav.metres(p,e)<65);
assert.equal(nav.polylineLength([p,e,n])>100,true);
assert.equal(nav.polylineLength([]),0);
assert.ok(Math.abs(nav.bearing(p,e)-90)<1);
assert.ok(Math.abs(nav.bearing(e,n))<1);
assert.ok(nav.angleChange(90,0)<0,'left corner');
assert.ok(nav.angleChange(90,180)>0,'right corner');
let turn=nav.nextBend([p,e,n]);
assert.equal(turn.direction,'left');
assert.ok(turn.distance>45&&turn.distance<65);
turn=nav.nextBend([p,e,s]);
assert.equal(turn.direction,'right');
assert.equal(nav.nextBend([p,e,[62,129.002]]),null);
const g=nav.guidance([p,e,n],4300);
assert.equal(g.symbol,'↰');
assert.match(g.instruction,/налево/);
assert.ok(g.etaMinutes>60);
assert.equal(nav.guidance([p,e],0).symbol,'↑');
assert.equal(nav.guidance([p,[62,129.00005]],0).symbol,'◎');
assert.equal(nav.minutes(4300),60);
assert.equal(nav.formatDistance(500),'500 м');
assert.equal(nav.formatDistance(1500),'1,5 км');
assert.equal(nav.formatDistance(NaN),'—');
console.log('Walking navigation: bearings, turn hints, remaining metres, time and near-finish tests OK');
