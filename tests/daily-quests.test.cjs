'use strict';
const assert=require('node:assert/strict');
const {dayKey,offersForDay,rngForOffer,qualifiedCompletion}=require('../daily-quests.js');
const day="2026-11-11",next="2026-11-12",at=Date.parse("2026-11-11T06:30:00Z");
const today=offersForDay(day),tomorrow=offersForDay(next);
assert.equal(dayKey(at),day);
assert.equal(dayKey(Date.parse("2026-11-11T14:59:59Z")),day);
assert.equal(dayKey(Date.parse("2026-11-11T15:00:00Z")),next);
assert.equal(today.length,3);
assert.equal(tomorrow.length,3);
assert(today.every(x=>x.day===day&&x.distanceKm>=2&&x.distanceKm<=6));
assert(today.every(x=>x.id.startsWith(day)&&x.reward>=30&&x.reward<=70));
assert.deepEqual(today.map(x=>x.reward),[30,50,70]);
assert.notDeepEqual(today.map(x=>x.id),tomorrow.map(x=>x.id));
assert.deepEqual(offersForDay(day),today);
assert.deepEqual(Array.from({length:10},()=>rngForOffer("same")()), Array.from({length:10},()=>rngForOffer("same")())); // first draw from fresh RNG each time
const r1=rngForOffer(today[0].seed),r2=rngForOffer(today[0].seed);
assert.deepEqual(Array.from({length:20},()=>r1()),Array.from({length:20},()=>r2()));
assert.notDeepEqual(Array.from({length:5},()=>rngForOffer(today[0].seed)()),Array.from({length:5},()=>rngForOffer(today[1].seed)()));
assert.equal(qualifiedCompletion([],day),null);
const evt=(id,dayVal=day,eligible=true,time=at)=>({key:"route_completed:"+id,type:"route_completed",at:time,
 data:{dailyEligible:eligible,dailyOfferId:id,dailyOfferDay:dayVal}});
assert.equal(qualifiedCompletion([evt(today[0].id)],day)?.data.dailyOfferId,today[0].id);
assert.equal(qualifiedCompletion([evt(today[0].id,day,false)],day),null);
assert.equal(qualifiedCompletion([evt(tomorrow[0].id)],day),null);
assert.equal(qualifiedCompletion([evt(today[0].id,next)],day),null);
assert.equal(qualifiedCompletion([evt(day+":not-an-offer")],day),null);
assert.equal(qualifiedCompletion([evt(today[0].id,day,true,Date.parse("2026-11-11T16:00:00Z"))],day),null);
assert.equal(qualifiedCompletion([{...evt(today[0].id),type:"photo_verified"}],day),null);
console.log("Daily routes: 21 verifications passed");
